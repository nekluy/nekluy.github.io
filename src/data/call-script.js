/* Интенты, которые не должны упираться в заглушку ни на одном шаге:
   «не слышно» — повторить, «не понимаю» — объяснить проще, «нет денег» —
   успокоить, «некогда» — попросить минуту. Ставятся только там, где шаг
   не задал своё поведение. */
const COMMON_ROUTES = {
  badAudio: { say: "again", reask: true },
  unsure: { say: "reassure", reask: true },
  money: { say: "money", reask: true },
  busy: { say: "hold_on", reask: true },
};

for (const step of Object.values(STEPS)) {
  if (step.end) continue;
  step.routes = { ...COMMON_ROUTES, ...step.routes };
  /* «нет» без уточнений: на вопрос «слышно?» — переспросить, иначе — как отказ */
  step.routes.no = step.routes.no ?? step.routes.refuse ?? { say: "bridge", reask: true };
}

/* Нормализация: регистр, ё → е, пунктуация и лишние пробелы. */
export function normalize(text) {
  return String(text ?? "")
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^а-я0-9\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

