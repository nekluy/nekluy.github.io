/**
 * Что человек имел в виду. Шаг важен: код ищется только там, где его ждут,
 * а «да» в начале фразы не должно перебивать отказ.
 */
export function classifyUtterance(text, step) {
  const t = normalize(text);
  if (!t) return "offtopic";
  const expectsCode = Boolean(step?.expectsCode);

  if (expectsCode) {
    const code = pickCode(t);
    if (code && code.length >= 3 && code.length <= 6) return "code";
  }
  if (RE.badAudio.test(t)) return "badAudio";
  if (RE.money.test(t)) return "money";
  if (RE.busy.test(t)) return "busy";
  if (RE.unsure.test(t)) return "unsure";
  if (RE.no.test(t)) return "no";
  if (RE.refuse.test(t)) return "refuse";
  if (RE.bye.test(t)) return "bye";
  if (RE.doubt.test(t)) return "doubt";
  if (RE.codeQuestion.test(t)) return "codeQuestion";
  if (RE.who.test(t)) return "who";
  if (RE.whatWant.test(t)) return "whatWant";
  if (RE.yes.test(t)) return "yes";
  if (RE.agree.test(t)) return "yes";
  return "offtopic";
}

const DIGIT_WORDS = {
  ноль: "0", нуль: "0", один: "1", одна: "1", два: "2", две: "2", три: "3",
  четыре: "4", пять: "5", шесть: "6", семь: "7", восемь: "8", девять: "9",
};

/** Код из речи: цифрами («4821») или словами («четыре восемь два один»). */
export function pickCode(text) {
  const raw = String(text ?? "");
  const digits = raw.match(/\d[\d\s]{2,}\d/);
  if (digits) return digits[0].replace(/\s/g, "");
  const words = normalize(raw).split(" ").filter(Boolean);
  const found = [];
  for (const word of words) {
    if (DIGIT_WORDS[word]) found.push(DIGIT_WORDS[word]);
  }
  return found.length >= 3 ? found.join("") : null;
}
